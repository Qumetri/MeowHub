// Two complete dictionaries (ru / en); scripts/check-i18n.mjs fails the build when
// a key is missing from either or a {placeholder} differs. The effective
// language comes from the server (/api/me `lang`); at boot we guess it from
// Telegram's language_code (and the last known value) to avoid a flash.
let current = 'ru'
export const getLang = () => current
export function setLang(code) {
  current = code === 'en' ? 'en' : 'ru'
  document.documentElement.lang = current
  return current
}

// Same rule as the server's i18n.resolve: ru/uk/be/kk -> ru, other non-empty -> en, empty -> ru.
export function resolveLang(code) {
  const c = String(code || '').toLowerCase().split(/[-_]/)[0]
  if (!c) return 'ru'
  return ['ru', 'uk', 'be', 'kk'].includes(c) ? 'ru' : 'en'
}

const LANG_KEY = 'mh_lang'
export function cachedLang() {
  try { const v = localStorage.getItem(LANG_KEY); return v === 'en' || v === 'ru' ? v : null } catch { return null }
}
export function cacheLang(code) {
  try { localStorage.setItem(LANG_KEY, code) } catch { /* private mode */ }
}

export const hasKey = (key) => (current === 'en' ? key in en : key in ru)

export function t(key, vars) {
  let s = (current === 'en' ? en[key] : undefined) ?? ru[key] ?? key
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''))
  return s
}

