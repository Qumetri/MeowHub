// Russian is the default and the only full dictionary for the owner's admin
// screens; English covers everything a member or stranger can see.
let current = 'ru'
export const getLang = () => current
export function setLang(code) {
  current = code && !String(code).toLowerCase().startsWith('ru') ? 'en' : 'ru'
  document.documentElement.lang = current
}

export function t(key, vars) {
  let s = (current === 'en' ? en[key] : undefined) ?? ru[key] ?? key
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''))
  return s
}

